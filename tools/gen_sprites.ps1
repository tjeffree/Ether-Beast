# Converts the ASCII sprite art in sprites/*.txt into:
#   firmware/EtherBeast/sprites.h  - 4-bit shade maps in PROGMEM for the CoreInk
#   sprites.js                     - the same art for the GitHub Pages dashboard
#
# Sprite files: body_<n>_<name>.txt (32x32) and face_<n>_<name>.txt (12x8).
# Shades, lightest to darkest: '.' paper, ':' 25%, '+' 50%, '%' 75%, '#' ink.
# The CoreInk renders the greys as dot patterns; '.' in a face is transparent.
# Lines starting with ';' are comments.

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$shades = '.:+%#'

function Read-Sprite($file, $w, $h) {
    $rows = @(Get-Content $file | Where-Object { $_ -notmatch '^\s*;' -and $_.Trim() -ne '' } | ForEach-Object { $_.TrimEnd() })
    if ($rows.Count -ne $h) { throw "$($file.Name): expected $h rows, found $($rows.Count)" }
    for ($i = 0; $i -lt $rows.Count; $i++) {
        if ($rows[$i].Length -ne $w) { throw "$($file.Name) row ${i}: expected $w chars, found $($rows[$i].Length)" }
        if ($rows[$i] -notmatch '^[.:+%#]+$') { throw "$($file.Name) row ${i}: only '.', ':', '+', '%' and '#' allowed" }
    }
    $rows
}

# Two pixels per byte, high nibble first; each nibble is a shade 0 (paper) to 4 (ink).
function To-Bytes($rows, $w) {
    $bytes = New-Object System.Collections.Generic.List[string]
    foreach ($row in $rows) {
        for ($x = 0; $x -lt $w; $x += 2) {
            $b = ($shades.IndexOf($row[$x]) -shl 4) -bor $shades.IndexOf($row[$x + 1])
            $bytes.Add(('0x{0:X2}' -f $b))
        }
    }
    $bytes
}

# The same rows for the dashboard, as shade digits 0-4.
function To-Digits($row) {
    -join ($row.ToCharArray() | ForEach-Object { $shades.IndexOf($_) })
}

$groups = @(
    @{ Prefix = 'body'; W = 32; H = 32; Array = 'BODY_SPRITES'; Key = 'bodies' },
    @{ Prefix = 'face'; W = 12; H = 8;  Array = 'FACE_SPRITES'; Key = 'faces' }
)

$h = @('#pragma once', '// Generated by tools/gen_sprites.ps1 from sprites/*.txt - edit the .txt files, not this.', '#include <Arduino.h>', '',
       'struct Sprite { uint8_t w, h; const uint8_t* shades; };  // 4 bits per pixel, high nibble first', '')
$js = @('// Generated by tools/gen_sprites.ps1 from sprites/*.txt - edit the .txt files, not this.', 'window.ETHER_SPRITES = {')

foreach ($g in $groups) {
    $files = Get-ChildItem "$root\sprites" -Filter "$($g.Prefix)_*.txt" | Sort-Object { [int]($_.BaseName -split '_')[1] }
    $entries = @(); $jsEntries = @()
    foreach ($f in $files) {
        $rows = Read-Sprite $f $g.W $g.H
        $name = 'SPR_' + $f.BaseName.ToUpper()
        $h += "static const uint8_t ${name}[] PROGMEM = {"
        $bytes = To-Bytes $rows $g.W
        $perLine = $g.W / 2
        for ($i = 0; $i -lt $bytes.Count; $i += $perLine) {
            $h += '  ' + (($bytes[$i..([Math]::Min($i + $perLine, $bytes.Count) - 1)]) -join ', ') + ','
        }
        $h += '};'
        $entries += "  { $($g.W), $($g.H), $name },  // $($f.BaseName)"
        $jsEntries += "    [`n" + (($rows | ForEach-Object { "      '$(To-Digits $_)'" }) -join ",`n") + "`n    ]"
    }
    $h += "static const Sprite $($g.Array)[] = {"
    $h += $entries
    $h += '};'
    $h += "static const uint8_t $($g.Array)_COUNT = $($files.Count);"
    $h += ''
    $js += "  $($g.Key): [`n" + ($jsEntries -join ",`n") + "`n  ],"
}
$js += '};'

Set-Content -Path "$root\firmware\EtherBeast\sprites.h" -Value $h -Encoding utf8NoBOM
Set-Content -Path "$root\sprites.js" -Value $js -Encoding utf8NoBOM
Write-Host "Wrote sprites.h and sprites.js"
